'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const sb=fs.readFileSync(path.join(root,'soundbank.js'),'utf8');
assert.match(html,/id="pauseButton"/);
assert.match(html,/id="pauseCover" hidden/);
assert.match(html,/id="resumeButton"/);
assert.match(html,/if\(paused\)\{\$\('board'\)\.replaceChildren\(\);return;\}/);
assert.match(html,/paused=!won&&!!data.paused/);
assert.match(html,/won,paused,engineVersion/);
assert.match(html,/paused=!won&&!!data\.paused/);
assert.match(html,/if\(!puzzle\|\|won\|\|paused\)return;/);
assert.match(html,/if\(v!==null\)playPlacementSound\(v\)/);
const bank={window:{}};
vm.runInNewContext(sb,bank);
assert.equal(bank.window.TRIANGO_SOUNDBANK.length,3);
for(const [i,uri] of bank.window.TRIANGO_SOUNDBANK.entries()){
 assert.ok(uri.startsWith('data:audio/mpeg;base64,'),`Sound ${i} has incorrect type`);
 const bytes=Buffer.from(uri.slice('data:audio/mpeg;base64,'.length),'base64');
 assert.equal(bytes.length,6312,`Sound ${i} missing data`);
 assert.ok(bytes.slice(0,3).toString('ascii')==='ID3'||bytes[0]===255,'Invalid MP3');
}
let now=0,renders=0,saves=0;
const timer=html.slice(html.indexOf('function syncClock(){'),html.indexOf('function setFeedback('));
const pause=html.slice(html.indexOf('function togglePause(){'),html.indexOf("$('pauseButton').addEventListener",html.indexOf('function togglePause(){')));
assert.ok(timer.includes('function getSeconds()') && pause.includes('paused=true'));
const nodes={hintPanel:{hidden:false},timer:{textContent:''}};
const ctx=vm.createContext({Date:{now:()=>now},Math,console});
vm.runInContext(`let puzzle={},won=false,paused=false,elapsed=0,secondsAnchor=0,hintShown={};
const $=(id)=>globalThis.nodes[id];
const render=()=>globalThis.record('render');
const serialize=()=>globalThis.record('save');
const setFeedback=()=>{};
const formatTime=(x)=>String(x);
${timer}
${pause}
globalThis.state=()=>({elapsed,paused,secondsAnchor,seconds:getSeconds(),hintShown});
globalThis.control=()=>togglePause();`,ctx);
ctx.nodes=nodes;ctx.record=(name)=>{if(name==='render')renders++;else saves++;};
now=6300;
assert.equal(ctx.state().seconds,6);
ctx.control();
assert.equal(ctx.state().seconds,6);
assert.equal(ctx.state().paused,true);
assert.equal(nodes.hintPanel.hidden,true);
now=30000;
assert.equal(ctx.state().seconds,6,'Clock must remain frozen during pause');
ctx.control();
assert.equal(ctx.state().paused,false);
assert.equal(ctx.state().seconds,6,'Resume must not count paused time');
now=34200;
assert.equal(ctx.state().seconds,10,'Clock should resume correctly');
assert.equal(renders,2);
assert.equal(saves,2);
console.log('PASS: 3 embedded MP3s, hidden grid, persisted pause flag, timer freeze/resume, guarded moves.');
